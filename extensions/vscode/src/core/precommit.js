import fs from "node:fs";
import path from "node:path";
import * as git from "./git";
import { BEGIN, STAGES, hookPath } from "./hooks";

export const CONFIG_FILE = ".pre-commit-config.yaml";
// Written by the pre-commit framework into every hook it installs.
const FRAMEWORK_MARKER = "File generated by pre-commit";
const SWEEPITO_REPO = /coldsofttech\/sweepito|id:\s*sweepito-(clean|scan)/i;

const read = (file) => (fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "");

/**
 * How the pre-commit framework (https://pre-commit.com) is involved in `root`:
 * { configFile, configured, managed, shadowed } where `configured` means the config runs
 * Sweepito, `managed[stage]` means the framework generated that hook, and `shadowed[stage]`
 * means a Sweepito block sits in such a hook (the framework's script ends with `exec`, so the
 * block never runs).
 */
export async function detect(root) {
    const top = (await git.toplevel(root)) ?? root;
    const configFile = path.join(top, CONFIG_FILE);
    const hasConfig = fs.existsSync(configFile);
    /** @type {Record<string, boolean>} */
    const managed = {};
    /** @type {Record<string, boolean>} */
    const shadowed = {};
    for (const stage of Object.keys(STAGES)) {
        const text = read(await hookPath(root, stage));
        managed[stage] = text.includes(FRAMEWORK_MARKER);
        shadowed[stage] = managed[stage] && text.includes(BEGIN);
    }
    return {
        configFile: hasConfig ? configFile : null,
        configured: hasConfig && SWEEPITO_REPO.test(read(configFile)),
        managed,
        shadowed,
    };
}

/** Throws if a Sweepito block added to this stage's hook could never run. */
export async function assertInstallable(root, stage) {
    if ((await detect(root)).managed[stage]) {
        throw new Error(
            `The ${stage} hook is generated by the pre-commit framework, and its script ends with exec, so an added ` +
                `Sweepito block would never run. Add Sweepito to ${CONFIG_FILE} instead (see the Sweepito README).`,
        );
    }
}
